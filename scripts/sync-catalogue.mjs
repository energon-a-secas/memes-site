#!/usr/bin/env node
// Writes js/data.js from references-api's catalogue, the one list of every
// reference and meme the Energon community uses
// (projects/references-api/api/v2/catalogue.json).
//
// The bundled memes are the catalogue's `origin: "vault"` entries: files this
// site serves from assets/images/. Their names, categories and order come from
// there, so a bundled meme is added or changed in the catalogue and then
// synced here. Uploads stay live in Convex and are not part of data.js.
//
//   node scripts/sync-catalogue.mjs           write js/data.js
//   node scripts/sync-catalogue.mjs --check   exit 1 if js/data.js would change
//
// The catalogue is read from the sibling checkout in the monorepo, or from
// CATALOGUE=<path>. Exits 2 when it cannot be found.
//
// convex/memes.ts and convex/categories.ts import MEMES too, so a name that
// changes here only reaches the server after `make deploy`.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const DATA_PATH = 'js/data.js';
export const CATALOGUE = process.env.CATALOGUE || join(ROOT, '..', 'references-api', 'api', 'v2', 'catalogue.json');
const SITE = 'https://memes.neorgon.com/';
const WIDTH = 72;

const rule = (text) => text + '─'.repeat(Math.max(3, WIDTH - [...text].length));

/** The bundled memes, in catalogue order, in the shape data.js has always had. */
export function vaultMemes(catalogue) {
  return catalogue.entries
    .filter((entry) => entry.kind === 'meme' && entry.origin === 'vault')
    .map((entry, index) => {
      const url = (entry.media.find((item) => item.primary) ?? entry.media[0]).url;
      if (!url.startsWith(`${SITE}assets/images/`)) throw new Error(`${entry.id}: a vault meme must be a file under ${SITE}assets/images/, got ${url}`);
      const path = decodeURI(url.slice(SITE.length));
      return { name: entry.id, category: entry.category, path, ext: path.slice(path.lastIndexOf('.') + 1).toLowerCase(), id: index + 1 };
    });
}

function wrap(items, indent, width) {
  const lines = [];
  let line = '';
  for (const item of items) {
    const next = line ? `${line} ${item}` : item;
    if (line && indent.length + next.length > width) {
      lines.push(indent + line);
      line = item;
    } else line = next;
  }
  if (line) lines.push(indent + line);
  return lines;
}

export function render(catalogue) {
  const memes = vaultMemes(catalogue);
  const categories = [...new Set(memes.map((meme) => meme.category))].sort();
  const out = [
    rule('// ── Static meme data '),
    `// GENERATED by scripts/sync-catalogue.mjs from references-api's catalogue`,
    '// (projects/references-api/api/v2/catalogue.json): its vault memes, the',
    '// files in assets/images/. Do not edit here. Change the catalogue, then run',
    '// `make catalogue`. Uploads live in Convex and are not listed here.',
    '',
    'export const MEMES = [',
  ];
  // One commented group per run of a category, as the hand-kept file had.
  let index = 0;
  while (index < memes.length) {
    const category = memes[index].category;
    let end = index;
    while (end < memes.length && memes[end].category === category) end += 1;
    if (index > 0) out.push('');
    out.push(rule(`  // ── ${category} (${end - index}) `));
    for (const meme of memes.slice(index, end)) {
      out.push(`  { name: ${JSON.stringify(meme.name)}, category: ${JSON.stringify(meme.category)}, path: ${JSON.stringify(meme.path)}, ext: ${JSON.stringify(meme.ext)}, id: ${meme.id} },`);
    }
    index = end;
  }
  out.push('];', '', 'export const CATEGORIES = [', ...wrap(categories.map((category) => `${JSON.stringify(category)},`), '  ', WIDTH), '];', '');
  return out.join('\n');
}

export function readCatalogue(path = CATALOGUE) {
  return existsSync(path) ? JSON.parse(readFileSync(path, 'utf8')) : null;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes('--check');
  const catalogue = readCatalogue();
  if (!catalogue) {
    console.error(`sync-catalogue: no catalogue at ${CATALOGUE}. Clone references-api beside this repo or set CATALOGUE=<path>.`);
    process.exit(2);
  }
  const text = render(catalogue);
  const full = join(ROOT, DATA_PATH);
  const current = existsSync(full) ? readFileSync(full, 'utf8') : null;
  const count = vaultMemes(catalogue).length;
  if (current === text) console.log(`sync-catalogue: ${DATA_PATH} is current (${count} bundled memes).`);
  else if (check) {
    console.error(`sync-catalogue: ${DATA_PATH} is out of date with the catalogue. Run: make catalogue`);
    process.exit(1);
  } else {
    writeFileSync(full, text);
    console.log(`sync-catalogue: wrote ${DATA_PATH} (${count} bundled memes).`);
  }
}
